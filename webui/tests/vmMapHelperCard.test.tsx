import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { VmMapHelperCard } from '../src/pages/settings/VmMapHelperCard'
const mocks=vi.hoisted(()=>({api:vi.fn()}))
vi.mock('../src/api/client',()=>({api:mocks.api}))
vi.mock('../src/util/viewer',()=>({isLocalViewer:()=>true}))
afterEach(()=>{cleanup();vi.restoreAllMocks();vi.resetAllMocks();localStorage.clear()})
describe('VM map resource consent',()=>{
 it('never installs on page entry or when resource consent is declined',async()=>{
  mocks.api.mockResolvedValue({enabled:false,phase:'not-installed'})
  vi.spyOn(window,'confirm').mockReturnValue(false)
  render(<VmMapHelperCard />)
  fireEvent.click(await screen.findByRole('button',{name:'Set up VM-hosted map'}))
  expect(window.confirm).toHaveBeenCalledWith(expect.stringContaining('250 MB'))
  expect(window.confirm).toHaveBeenCalledWith(expect.stringContaining('500 MB'))
  expect(window.confirm).toHaveBeenCalledWith(expect.stringContaining('existing resources'))
  expect(window.confirm).toHaveBeenCalledWith(expect.stringContaining('automatically'))
  expect(mocks.api).toHaveBeenCalledTimes(1)
 })
 it('installs only after accepting the resource cost',async()=>{
  mocks.api.mockResolvedValue({enabled:false,phase:'not-installed'})
  vi.spyOn(window,'confirm').mockReturnValue(true)
  render(<VmMapHelperCard />)
  fireEvent.click(await screen.findByRole('button',{name:'Set up VM-hosted map'}))
  expect(mocks.api).toHaveBeenLastCalledWith('/api/v1/maps/vm-helper',{method:'POST',body:'{"resourcesAccepted":true}'})
 })
 it('keeps the map in DST and collection controls local',async()=>{
  mocks.api.mockResolvedValue({enabled:true,phase:'ready',live:true,refreshSeconds:3})
  render(<VmMapHelperCard />)
  expect(await screen.findByRole('link',{name:'Open Live Map'})).toHaveAttribute('href','/map?view=live')
  expect(screen.queryByText('Authorize VM')).not.toBeInTheDocument()
  expect(screen.getByRole('button',{name:'Refresh snapshot'})).toBeDisabled()
  expect(screen.getByRole('status')).toHaveTextContent('Stop live before refreshing a snapshot')
  fireEvent.click(screen.getByRole('button',{name:'Stop live'}))
  expect(mocks.api).toHaveBeenLastCalledWith('/api/v1/maps/vm-helper/control',{method:'POST',body:'{"action":"stop"}'})
 })
 it('keeps snapshot progress visible until collection finishes and blocks duplicate actions',async()=>{
  mocks.api.mockResolvedValueOnce({enabled:true,phase:'ready',live:false})
   .mockResolvedValueOnce({enabled:true,phase:'ready',live:false,refreshing:true})
   .mockResolvedValueOnce({enabled:true,phase:'ready',live:false,refreshing:false,activity:[]})
  render(<VmMapHelperCard />)
  fireEvent.click(await screen.findByRole('button',{name:'Refresh snapshot'}))
  await waitFor(()=>expect(screen.getByRole('status')).toHaveTextContent('Refreshing snapshot'))
  expect(screen.getByRole('button',{name:'Refresh snapshot'})).toBeDisabled()
  expect(screen.getByRole('button',{name:'Start live'})).toBeDisabled()
  expect(screen.queryByText('Setting up VM-hosted map…')).not.toBeInTheDocument()
  await waitFor(()=>expect(screen.getByRole('button',{name:'Refresh snapshot'})).toBeEnabled(),{timeout:3500})
  expect(screen.queryByRole('status')).not.toBeInTheDocument()
 })
 it('waits for Stop live to finish before enabling a snapshot',async()=>{
  mocks.api.mockResolvedValueOnce({enabled:true,phase:'ready',live:true})
   .mockResolvedValueOnce({enabled:true,phase:'ready',live:false,stopping:true})
  render(<VmMapHelperCard />)
  fireEvent.click(await screen.findByRole('button',{name:'Stop live'}))
  await waitFor(()=>expect(screen.getByRole('status')).toHaveTextContent('Stopping live collection'))
  expect(screen.getByRole('button',{name:'Refresh snapshot'})).toBeDisabled()
 })
})
