import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { api } from '../src/api/client'
import { SoloMods } from '../src/components/solo/SoloMods'
vi.mock('../src/api/client', () => ({api: vi.fn()}))
vi.mock('../src/util/pathPicker', () => ({pickLocalFolder: vi.fn()}))
const state = {mods: [{folder: 'Example', id: 'Example', name: 'Example', version: '1.0', enabled: false, warnings: ['Declares WPS Launcher'], errors: ['Missing or disabled dependency: Framework']}], folder: 'C:/DST/Mods', gamePath: 'C:/Dune', skipIntro: false, runtimeReady: true, session: null}
beforeEach(() => { vi.mocked(api).mockImplementation(async () => state) })
afterEach(() => { cleanup(); vi.clearAllMocks(); localStorage.clear() })
describe('Solo mod controls', () => {
  it('imports a dropped ZIP using its contents and refreshes the mod list', async () => {
    render(<SoloMods />)
    fireEvent.click(screen.getByRole('button', { name: /Solo mods/ }))
    await screen.findByText('Example')
    const file = new File(['zip fixture'], 'Example.zip', { type: 'application/zip' })
    fireEvent.drop(screen.getByRole('region', { name: 'Drop a mod ZIP' }), { dataTransfer: { types: ['Files'], files: [file] } })
    await waitFor(() => expect(api).toHaveBeenCalledWith('/api/solo/mods/import', {method:'POST',body:JSON.stringify({filename:'Example.zip',base64:btoa('zip fixture')})}))
    expect(await screen.findByText('Example.zip installed.')).toBeInTheDocument()
  })
  it('rejects non-ZIP and multiple file drops before uploading', async () => {
    render(<SoloMods />)
    fireEvent.click(screen.getByRole('button', { name: /Solo mods/ }))
    await screen.findByText('Example')
    const zone=screen.getByRole('region', {name:'Drop a mod ZIP'})
    fireEvent.drop(zone,{dataTransfer:{types:['Files'],files:[new File(['text'],'notes.txt')]}})
    expect(await screen.findByRole('alert')).toHaveTextContent('Drop one ZIP')
    fireEvent.drop(zone,{dataTransfer:{types:['Files'],files:[new File(['a'],'a.zip'),new File(['b'],'b.zip')]}})
    expect(api).not.toHaveBeenCalledWith('/api/solo/mods/import',expect.anything())
  })
  it('blocks file drops while Dune is running', async () => {
    vi.mocked(api).mockResolvedValue({...state,gameRunning:true})
    render(<SoloMods />)
    fireEvent.click(screen.getByRole('button', { name: /Solo mods/ }))
    await screen.findByText('Close Dune before installing a mod ZIP.')
    const zone=screen.getByRole('region',{name:'Drop a mod ZIP'})
    expect(zone).toHaveAttribute('aria-disabled','true')
    fireEvent.drop(zone,{dataTransfer:{types:['Files'],files:[new File(['a'],'a.zip')]}})
    expect(api).not.toHaveBeenCalledWith('/api/solo/mods/import',expect.anything())
  })
  it('shows the full UE4SS log in a dialog with a download action', async () => {
    vi.mocked(api).mockImplementation(async path => path === '/api/solo/mods/log' ? {available:true,content:'first mod line\nlast mod line'} : state)
    render(<SoloMods />)
    fireEvent.click(screen.getByRole('button', {name:/Solo mods/}))
    fireEvent.click(await screen.findByRole('button', {name:'View UE4SS Log'}))
    expect(await screen.findByRole('alertdialog')).toHaveTextContent('first mod line')
    expect(screen.getByRole('button', {name:'Download UE4SS.log'})).toBeInTheDocument()
    const createURL=vi.fn(() => 'blob:runtime-log')
    Object.defineProperty(URL,'createObjectURL',{configurable:true,value:createURL})
    Object.defineProperty(URL,'revokeObjectURL',{configurable:true,value:vi.fn()})
    const click=vi.spyOn(HTMLAnchorElement.prototype,'click').mockImplementation(function () {
      expect(this.download).toBe('UE4SS.log')
      expect(this.href).toBe('blob:runtime-log')
    })
    fireEvent.click(screen.getByRole('button', {name:'Download UE4SS.log'}))
    expect(createURL).toHaveBeenCalledWith(expect.any(Blob))
    expect(click).toHaveBeenCalledOnce()
    click.mockRestore()
    fireEvent.click(screen.getByRole('button', {name:'Close'}))
    await waitFor(() => expect(screen.queryByRole('alertdialog')).not.toBeInTheDocument())
  })
  it('explains when no log is available without offering an empty download', async () => {
    vi.mocked(api).mockImplementation(async path => path === '/api/solo/mods/log' ? {available:false,content:''} : state)
    render(<SoloMods />)
    fireEvent.click(screen.getByRole('button', {name:/Solo mods/}))
    fireEvent.click(await screen.findByRole('button', {name:'View UE4SS Log'}))
    expect(await screen.findByRole('alertdialog')).toHaveTextContent('No log yet')
    expect(screen.queryByRole('button', {name:'Download UE4SS.log'})).not.toBeInTheDocument()
  })
  it('loads and saves Launch Arguments while the mod list is collapsed', async () => {
    vi.mocked(api).mockImplementation(async () => ({...state, soloArguments:'-log'}))
    render(<SoloMods />)
    const input = await screen.findByPlaceholderText('Optional command line arguments')
    await waitFor(() => expect(input).toHaveValue('-log'))
    expect(screen.getByText('Launch Arguments')).toBeVisible()
    fireEvent.change(input, {target:{value:'-example="two words"'}})
    fireEvent.click(screen.getByRole('button', {name:'Save arguments'}))
    await waitFor(() => expect(api).toHaveBeenCalledWith('/api/game/launch-preferences', {method:'POST',body:JSON.stringify({soloArguments:'-example="two words"'})}))
  })
  it('keeps the installation folder and launch errors visible when collapsed', async () => {
    vi.mocked(api).mockImplementation(async path => {
      if (path === '/api/solo/mods/launch') throw new Error('Select the Dune Awakening installation folder in Solo mods and save it before launching.')
      return {...state, gamePath:''}
    })
    render(<SoloMods />)
    expect(screen.getByRole('button', {name:/Solo mods/})).toHaveAttribute('aria-expanded', 'false')
    expect(screen.getByPlaceholderText('Select your Dune Awakening installation folder')).toBeVisible()
    fireEvent.click(screen.getByRole('button', {name:'Launch with Mods'}))
    expect(await screen.findByRole('alert')).toHaveTextContent('installation folder')
    expect(screen.getByRole('button', {name:'Browse'})).toBeVisible()
  })
  it('requires confirmation before deleting a mod and allows cancellation', async () => {
    render(<SoloMods />)
    fireEvent.click(screen.getByRole('button', {name:/Solo mods/}))
    await screen.findByText('Example')
    fireEvent.click(screen.getByRole('button', {name:'Delete Example'}))
    expect(screen.getByRole('alertdialog')).toHaveTextContent('INI settings')
    fireEvent.click(screen.getByRole('button', {name:'Cancel'}))
    expect(api).not.toHaveBeenCalledWith('/api/solo/mods/delete', expect.anything())
    fireEvent.click(screen.getByRole('button', {name:'Delete Example'}))
    fireEvent.click(screen.getByRole('button', {name:'Delete mod'}))
    await waitFor(() => expect(api).toHaveBeenCalledWith('/api/solo/mods/delete', {method:'POST',body:JSON.stringify({folder:'Example'})}))
  })
  it('saves the moved order and disables moves at the list boundaries', async () => {
    const other = {...state.mods[0], folder:'Other', id:'Other', name:'Other', enabled:true, errors:[]}
    vi.mocked(api).mockImplementation(async () => ({...state, mods:[state.mods[0], other]}))
    render(<SoloMods />)
    fireEvent.click(screen.getByRole('button', {name:/Solo mods/}))
    await screen.findByText('Example')
    expect(screen.getByRole('link', {name:/Browse Dune/})).toHaveAttribute('href', 'https://www.nexusmods.com/duneawakening')
    expect(screen.getByRole('button', {name:'Move Example up'})).toBeDisabled()
    expect(screen.getByRole('button', {name:'Move Other down'})).toBeDisabled()
    fireEvent.click(screen.getByRole('button', {name:'Move Other up'}))
    await waitFor(() => expect(api).toHaveBeenCalledWith('/api/solo/mods/selection', {method:'POST',body:JSON.stringify({mods:[other,state.mods[0]],gamePath:state.gamePath,platform:'steam'})}))
  })
  it('shows dependency errors and keeps normal and modded launches separate', async () => {
    render(<SoloMods />)
    expect(screen.getByRole('button', {name: /Solo mods/})).toHaveAttribute('aria-expanded', 'false')
    fireEvent.click(screen.getByRole('button', {name: /Solo mods/}))
    await screen.findByText('Example')
    expect(screen.getByText(/We make no guarantees.*does not provide individual mod troubleshooting/)).toBeInTheDocument()
    expect(screen.queryByText('Declares WPS Launcher')).not.toBeInTheDocument()
    expect(screen.getByText(/Missing or disabled dependency/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', {name: /Solo mods/}))
    expect(screen.queryByText('Example')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', {name: 'Launch Solo'}))
    await waitFor(() => expect(api).toHaveBeenCalledWith('/api/solo/mods/launch', {method:'POST',body:JSON.stringify({withMods:false})}))
    await waitFor(() => expect(screen.getByRole('button', {name:'Launch with Mods'})).toBeEnabled())
    fireEvent.click(screen.getByRole('button', {name: 'Launch with Mods'}))
    await waitFor(() => expect(api).toHaveBeenCalledWith('/api/solo/mods/launch', {method:'POST',body:JSON.stringify({withMods:true})}))
    expect(screen.getByRole('button', {name: /Solo mods/})).toHaveAttribute('aria-expanded', 'false')
  })
  it('imports the selected ZIP and preserves visible loader errors', async () => {
    vi.mocked(api).mockImplementation(async path => {
      if(path === '/api/browse-path') return {cancelled:false,path:'C:/Downloads/mod.zip'}
      if(path === '/api/solo/mods/import') throw new Error('Missing mod entry point')
      return state
    })
    render(<SoloMods />)
    fireEvent.click(screen.getByRole('button', {name: /Solo mods/}))
    await screen.findByText('Example')
    fireEvent.click(screen.getByRole('button', {name:'Install mod ZIP'}))
    await screen.findByRole('alert')
    expect(screen.getByRole('alert')).toHaveTextContent('Missing mod entry point')
    expect(api).toHaveBeenCalledWith('/api/solo/mods/import', {method:'POST',body:JSON.stringify({path:'C:/Downloads/mod.zip'})})
  })
})
